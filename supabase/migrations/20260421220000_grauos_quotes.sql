-- 1. CRIAR TABELA DE AUTORES
CREATE TABLE IF NOT EXISTS public.authors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  birth_year INT,
  death_year INT,
  nationality TEXT,
  main_work TEXT,
  specialty TEXT,
  color TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CRIAR TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.quote_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CRIAR TABELA PRINCIPAL DE CITAÇÕES
CREATE TABLE IF NOT EXISTS public.quotes (
  id TEXT PRIMARY KEY,
  author_id BIGINT NOT NULL REFERENCES public.authors(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES public.quote_categories(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  tags JSONB,
  source TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  view_count INT DEFAULT 0,
  favorite_count INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_quotes_author ON public.quotes(author_id);
CREATE INDEX IF NOT EXISTS idx_quotes_category ON public.quotes(category_id);
CREATE INDEX IF NOT EXISTS idx_quotes_active ON public.quotes(is_active);

-- 4. CRIAR TABELA DE USO (ANALYTICS)
CREATE TABLE IF NOT EXISTS public.quote_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id TEXT NOT NULL REFERENCES public.quotes(id) ON DELETE CASCADE,
  franchisee_id UUID REFERENCES auth.users(id),
  campaign_id TEXT,
  context TEXT,
  ip_address TEXT,
  used_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_quote_usage_quote ON public.quote_usage(quote_id);
CREATE INDEX IF NOT EXISTS idx_quote_usage_franchisee ON public.quote_usage(franchisee_id);
CREATE INDEX IF NOT EXISTS idx_quote_usage_used_at ON public.quote_usage(used_at);

-- 5. CRIAR TABELA DE FAVORITOS
CREATE TABLE IF NOT EXISTS public.quote_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id TEXT NOT NULL REFERENCES public.quotes(id) ON DELETE CASCADE,
  franchisee_id UUID NOT NULL REFERENCES auth.users(id),
  saved_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (quote_id, franchisee_id)
);

CREATE INDEX IF NOT EXISTS idx_quote_favorites_franchisee ON public.quote_favorites(franchisee_id);


