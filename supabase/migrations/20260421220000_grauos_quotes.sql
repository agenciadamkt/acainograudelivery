-- Everyone can read authors, categories, quotes:
CREATE POLICY "Public read authors" ON public.authors FOR SELECT USING (true);
CREATE POLICY "Public read categories" ON public.quote_categories FOR SELECT USING (true);
CREATE POLICY "Public read quotes" ON public.quotes FOR SELECT USING (is_active = true);

-- Users can insert usage and manage their own favorites
CREATE POLICY "Insert quote usage" ON public.quote_usage FOR INSERT WITH CHECK (true);
CREATE POLICY "Select quote usage" ON public.quote_usage FOR SELECT USING (franchisee_id = auth.uid());

CREATE POLICY "Manage favorites" ON public.quote_favorites FOR ALL USING (franchisee_id = auth.uid());


