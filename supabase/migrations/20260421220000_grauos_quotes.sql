-- ============================================================
-- CRIAR ROTINA (RPC) PARA BUSCAR UMA CITAÇÃO ALEATÓRIA
-- ============================================================
CREATE OR REPLACE FUNCTION get_random_quote(p_category_id BIGINT DEFAULT NULL)
RETURNS TABLE (
  id TEXT,
  text TEXT,
  author_name TEXT,
  author_color TEXT,
  category_name TEXT,
  source TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT 
    q.id,
    q.text,
    a.name AS author_name,
    a.color AS author_color,
    c.name AS category_name,
    q.source
  FROM public.quotes q
  JOIN public.authors a ON q.author_id = a.id
  JOIN public.quote_categories c ON q.category_id = c.id
  WHERE q.is_active = TRUE
    AND (p_category_id IS NULL OR q.category_id = p_category_id)
  ORDER BY RANDOM()
  LIMIT 1;
END;
$$;
